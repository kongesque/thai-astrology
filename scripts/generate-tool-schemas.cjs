'use strict'

// Development-only TypeScript reflection. Published modules need no schema library.
const ts = require('typescript')
const { readFileSync, writeFileSync } = require('node:fs')
const { resolve } = require('node:path')
const root = resolve(__dirname, '..')
const config = ts.readConfigFile(resolve(root, 'tsconfig.json'), ts.sys.readFile)
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root)
const program = ts.createProgram([resolve(root, 'src/tool-types.ts')], parsed.options)
const checker = program.getTypeChecker()
const diagnostics = ts.getPreEmitDiagnostics(program)
if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
  getCanonicalFileName: file => file, getCurrentDirectory: () => root, getNewLine: () => '\n',
}))
const file = program.getSourceFile(resolve(root, 'src/tool-types.ts'))
const exported = checker.getExportsOfModule(checker.getSymbolAtLocation(file))
const named = name => checker.getDeclaredTypeOfSymbol(exported.find(symbol => symbol.name === name))
const propertyType = symbol => checker.getTypeOfSymbolAtLocation(symbol, symbol.valueDeclaration || symbol.declarations?.[0] || file)

function schemaFor(type) {
  const definitions = {}, seen = new Map()
  function describe(value) {
    const flags = value.flags
    if (flags & (ts.TypeFlags.Unknown | ts.TypeFlags.Any)) return {}
    if (flags & ts.TypeFlags.Never) return { not: {} }
    if (flags & ts.TypeFlags.StringLiteral) return { const: value.value, type: 'string' }
    if (flags & ts.TypeFlags.NumberLiteral) return { const: value.value, type: 'number' }
    if (flags & ts.TypeFlags.BooleanLiteral) return { const: value.intrinsicName === 'true', type: 'boolean' }
    if (flags & ts.TypeFlags.String) return { type: 'string' }
    if (flags & ts.TypeFlags.Number) return { type: 'number' }
    if (flags & ts.TypeFlags.Boolean) return { type: 'boolean' }
    if (flags & ts.TypeFlags.Null) return { type: 'null' }
    if (value.isUnion()) {
      const members = value.types.filter(member => !(member.flags & ts.TypeFlags.Undefined))
      return { anyOf: members.map(describe) }
    }
    if (checker.isTupleType(value)) {
      const items = checker.getTypeArguments(value).map(describe)
      return { type: 'array', prefixItems: items, minItems: items.length, maxItems: items.length }
    }
    if (checker.isArrayType(value)) return { type: 'array', items: describe(checker.getTypeArguments(value)[0]) }
    if (flags & ts.TypeFlags.Object || value.isIntersection() && value.types.every(member => member.flags & ts.TypeFlags.Object)) {
      if (seen.has(value)) return { $ref: `#/$defs/${seen.get(value)}` }
      const name = `object${seen.size + 1}`
      seen.set(value, name)
      const properties = {}, required = []
      const schema = { type: 'object', properties, additionalProperties: false }
      definitions[name] = schema
      for (const property of checker.getPropertiesOfType(value)) {
        const description = ts.displayPartsToString(property.getDocumentationComment(checker))
        properties[property.name] = { ...describe(propertyType(property)), ...(description ? { description } : {}) }
        if (!(property.flags & ts.SymbolFlags.Optional)) required.push(property.name)
      }
      if (required.length) schema.required = required
      const index = checker.getIndexTypeOfType(value, ts.IndexKind.String)
      if (index) schema.additionalProperties = describe(index)
      return { $ref: `#/$defs/${name}` }
    }
    throw new Error(`Unsupported schema type: ${checker.typeToString(value)}`)
  }
  const schema = describe(type)
  // Object roots are explicit for tool hosts that require type: object.
  const expanded = schema.$ref ? definitions[schema.$ref.split('/').pop()] : schema
  return { $schema: 'https://json-schema.org/draft/2020-12/schema', ...expanded, ...(Object.keys(definitions).length ? { $defs: definitions } : {}) }
}
const results = named('AstrologyToolResults')
const schemas = Object.fromEntries(checker.getPropertiesOfType(named('AstrologyToolInputs')).map(property => [property.name, {
  inputSchema: schemaFor(propertyType(property)),
  outputSchema: schemaFor(propertyType(checker.getPropertyOfType(results, property.name))),
}]))
const output = `// Generated by npm run schemas. Edit public types, then regenerate.\nimport type { AstrologyToolName } from "./tool-types"\n\nexport type AstrologyJsonSchema = Record<string, unknown>\nexport interface AstrologyToolSchemas { inputSchema: AstrologyJsonSchema; outputSchema: AstrologyJsonSchema }\n\nconst schemas: Record<AstrologyToolName, AstrologyToolSchemas> = ${JSON.stringify(schemas, null, 2)}\n\n/** Fresh JSON Schema 2020-12 contracts; domain/date validation remains in the engine. */\nexport function getThaiAstrologySchemas(): Record<AstrologyToolName, AstrologyToolSchemas> {\n  return JSON.parse(JSON.stringify(schemas)) as Record<AstrologyToolName, AstrologyToolSchemas>\n}\n`
const target = resolve(root, 'src/schemas.ts')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Tool schemas are stale. Run npm run schemas.')
} else writeFileSync(target, output)
